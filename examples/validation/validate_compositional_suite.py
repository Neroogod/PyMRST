def main() -> int:
    failures: list[str] = []
    print("\nPyMRST compositional MATLAB-regression suite")
    for script in COMPOSITIONAL_VALIDATORS:
        path = HERE / script
        if not path.exists():
            failures.append(f"{script}: missing")
            print(f"\nFAIL {script}: missing")
            continue
        print(f"\n=== {script} ===")
        result = subprocess.run([sys.executable, str(path)], cwd=HERE.parent.parent)
        if result.returncode != 0:
            failures.append(f"{script}: exit {result.returncode}")

    if failures:
        print("\nCompositional suite failed:")
        for failure in failures:
            print(f"  - {failure}")
        return 1

    print("\nCompositional suite passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


